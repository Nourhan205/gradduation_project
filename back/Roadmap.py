import re

def parse_roadmap_string(roadmap_str):
    parsed_roadmap = {}
    current_phase = None

    lines = roadmap_str.split('\n')

    # Skip introductory text until the first phase header is found
    roadmap_content_started = False
    for line in lines:
        if line.strip().startswith('###'):
            roadmap_content_started = True
            break

    if not roadmap_content_started:
        return {} # Return empty if no structured roadmap content found

    # Process lines from where the structured roadmap begins
    for line in lines:
        line_trimmed = line.strip()
        if not line_trimmed:
            continue

        if line_trimmed.startswith('###'):
            # This is a new phase header
            phase_name_match = re.match(r'###\s*(.*)', line_trimmed)
            if phase_name_match:
                current_phase = phase_name_match.group(1).strip()
                parsed_roadmap[current_phase] = []
        elif current_phase is not None:
            # This is a task bullet point (can be indented)
            bullet_match = re.match(r'^\s*[-*]\s*(.*)', line)
            if bullet_match:
                task = bullet_match.group(1).strip()
                # Remove markdown bolding if present
                task = re.sub(r'\*\*([^*]+)\*\*', r'\1', task)
                if task:
                    parsed_roadmap[current_phase].append(task)

    # Filter out any phases that ended up empty
    parsed_roadmap = {k: v for k, v in parsed_roadmap.items() if v}
    return parsed_roadmap

# Parse the roadmap string into a dictionary
parsed_roadmap_dict = parse_roadmap_string(roadmap)

# Call plot_roadmap with the parsed dictionary
plot_roadmap(parsed_roadmap_dict, title="Learning Roadmap")