import plotly.graph_objects as go

def plot_roadmap(roadmap, title="Learning Roadmap"):
    """
    roadmap: dict
        مثال:
        {
            "Phase 1": ["Task 1", "Task 2"],
            "Phase 2": ["Task 1", "Task 2"]
        }
    title: str
        عنوان الصورة
    """
    phases = list(roadmap.keys())
    colors = ["#636EFA", "#EF553B", "#00CC96", "#AB63FA", "#FFA15A", "#19D3F3"]

    fig = go.Figure()

    for i, phase in enumerate(phases):
        tasks = roadmap[phase]
        fig.add_trace(go.Bar(
            y=[phase]*len(tasks),
            x=[1]*len(tasks),
            orientation='h',
            text=tasks,
            textposition='inside',
            marker_color=colors[i % len(colors)],
            name=phase
        ))

    fig.update_layout(
        title=title,
        barmode='stack',
        xaxis=dict(showticklabels=False),
        yaxis=dict(autorange="reversed"),
        height=400 + 50*len(phases),
        showlegend=False
    )

    fig.show()


    fig.write_image("roadmap.png")  # PNG
    #fig.write_image("roadmap.pdf")  # PDF

from transformers import AutoModelForCausalLM, AutoTokenizer
import torch

model_name = "Qwen/Qwen2.5-3B-Instruct"

tokenizer = AutoTokenizer.from_pretrained(model_name, trust_remote_code=True)
model = AutoModelForCausalLM.from_pretrained(
    model_name,
    torch_dtype=torch.float16,
    device_map="auto",
    trust_remote_code=True
)

def generate_roadmap(user_input):
    prompt = f"""
You are an expert learning planner.

The user wants a roadmap.

User request:
"{user_input}"

Create a clear and structured roadmap.
Divide it into phases or months.
Use simple bullet points.
"""

    inputs = tokenizer(prompt, return_tensors="pt").to(model.device)

    outputs = model.generate(
        **inputs,
        max_new_tokens=600,
        temperature=0.7
    )

    return tokenizer.decode(outputs[0], skip_special_tokens=True)


